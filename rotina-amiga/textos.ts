export const criarT = (idioma: Idioma) => (k: ChaveTexto): string => {
  const e = extra[idioma] as Record<string, string>;
  const b = (base as Record<string, Record<string, string>>)[idioma];
  return e[k] ?? b[k] ?? (extra.pt as Record<string, string>)[k] ?? (base.pt as Record<string, string>)[k] ?? String(k);
};

export const normalizarIdioma = (x?: string): Idioma => {
  const s = (x || 'pt').toLowerCase();
  if (s.startsWith('en')) return 'en';
  if (s.startsWith('es')) return 'es';
  return 'pt';
};
